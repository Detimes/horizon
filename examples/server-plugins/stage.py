#!/usr/bin/env python3
"""Stage a dedicated server build with the plugin host linked in, as the launcher's generated
executable does for a trait mod (launcher/src/native_mods/api.rs), without the launcher.

    python3 examples/server-plugins/stage.py <stage dir>
    cd <stage dir> && cargo build --profile fast -p horizon-native-game --no-default-features
    # -> <stage dir>/target/fast/horizon-client, run with --dedicated

The source is this checkout's HEAD, exported once; later runs only rewrite files whose text
changed, so cargo builds incrementally.
"""
import pathlib
import subprocess
import sys

HERE = pathlib.Path(__file__).resolve().parent
REPO = HERE.parent.parent


def put(path: pathlib.Path, text: str) -> None:
    if path.exists() and path.read_text() == text:
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)


def sync(src: pathlib.Path, dst: pathlib.Path, rewrite=None) -> None:
    for f in src.rglob("*"):
        if f.is_file() and "target" not in f.parts:
            text = f.read_text()
            if rewrite and f.name == "Cargo.toml":
                text = rewrite(text)
            put(dst / f.relative_to(src), text)


MAIN = """//! Generated by stage.py, as the launcher generates it for trait mods.
#![forbid(unsafe_code)]

#[global_allocator]
static ALLOCATOR: horizon_threads::Allocator = horizon_threads::ALLOCATOR;

static MOD_API_LEVEL: [u8; horizon_mods::api_level::MARK.len()] = horizon_mods::api_level::MARK;

fn main() {
    std::hint::black_box(&MOD_API_LEVEL);
    let mods: horizon_client::mod_api::Mods = vec![mod_0::hooks()].into();
    horizon_client::mod_api::name_mods(&["pluginhost"]);
    horizon_client::entry::main_with(mods);
}
"""


def game_manifest(stage: pathlib.Path) -> str:
    client = (stage / "crates/horizon-client/Cargo.toml").read_text()
    build_deps = ""
    if "[build-dependencies]" in client:
        section = client.split("[build-dependencies]", 1)[1].split("\n[", 1)[0]
        build_deps = "[build-dependencies]" + section.rstrip() + "\n"
    return f"""[package]
name = "horizon-native-game"
version = "0.1.0"
edition = "2024"
publish = false
build = "../horizon-client/build.rs"

[[bin]]
name = "horizon-client"
path = "src/main.rs"

[dependencies]
horizon-client = {{ path = "../horizon-client", default-features = false }}
horizon-threads = {{ path = "../horizon-threads" }}
horizon-mods = {{ path = "../horizon-mods" }}
mod_0 = {{ path = "../../native-api/pluginhost", package = "mod-pluginhost" }}

[features]
default = ["horizon-client/default"]

{build_deps}"""


def main() -> None:
    stage = pathlib.Path(sys.argv[1]).resolve()
    if not (stage / "Cargo.toml").exists():
        stage.mkdir(parents=True, exist_ok=True)
        archive = subprocess.run(["git", "-C", str(REPO), "archive", "HEAD"], check=True, capture_output=True)
        subprocess.run(["tar", "-x", "-C", str(stage)], input=archive.stdout, check=True)
    sync(HERE / "abi", stage / "native-api/horizon-plugin-abi")
    sync(
        HERE / "loader",
        stage / "native-api/horizon-plugin-loader",
        lambda t: t.replace('path = "../abi"', 'path = "../horizon-plugin-abi"'),
    )
    sync(
        HERE / "host/api",
        stage / "native-api/pluginhost",
        lambda t: t.replace(
            'horizon-client = { git = "https://github.com/horizon-rust/horizon" }',
            'horizon-client = { path = "../../crates/horizon-client", default-features = false }',
        ).replace('path = "../../loader"', 'path = "../horizon-plugin-loader"'),
    )
    put(stage / "crates/native-game/src/main.rs", MAIN)
    put(stage / "crates/native-game/Cargo.toml", game_manifest(stage))
    root = stage / "Cargo.toml"
    text = root.read_text()
    members = ["native-api/horizon-plugin-abi", "native-api/horizon-plugin-loader", "native-api/pluginhost", "crates/native-game"]
    extra = "".join(f'    "{m}",\n' for m in members if f'"{m}"' not in text)
    if extra:
        root.write_text(text.replace('    "xtask",\n', '    "xtask",\n' + extra, 1))
    print(stage)


if __name__ == "__main__":
    main()
